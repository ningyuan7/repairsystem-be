CREATE TABLE repair_delivery_jobs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, notification_id BIGINT UNSIGNED NOT NULL, channel VARCHAR(16) NOT NULL DEFAULT 'EMAIL',
 status VARCHAR(16) NOT NULL DEFAULT 'QUEUED', attempts INT UNSIGNED NOT NULL DEFAULT 0, next_run_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 lease_token CHAR(36), lease_until DATETIME(3), last_error_code VARCHAR(128), created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(notification_id,channel), INDEX(status,next_run_at), CHECK(channel='EMAIL'), CHECK(status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','CANCELLED')),
 FOREIGN KEY(notification_id) REFERENCES repair_notifications(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_sla_marks (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ticket_id BIGINT UNSIGNED NOT NULL, kind VARCHAR(16) NOT NULL, cycle_key VARCHAR(64) NOT NULL,
 due_at DATETIME(3) NOT NULL, notified_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(ticket_id,kind,cycle_key), CHECK(kind IN ('REVIEW','ACCEPT','REPAIR','ACCEPTANCE')), FOREIGN KEY(ticket_id) REFERENCES repair_tickets(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
