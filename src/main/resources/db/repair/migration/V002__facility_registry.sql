CREATE TABLE repair_categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(32) NOT NULL UNIQUE, name VARCHAR(128) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', version INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CHECK(status IN ('ACTIVE','DISABLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_assets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, store_id BIGINT UNSIGNED NOT NULL, asset_code VARCHAR(64) NOT NULL,
 name VARCHAR(128) NOT NULL, zone VARCHAR(128) NOT NULL, brand VARCHAR(128), model VARCHAR(128), serial_number VARCHAR(128),
 lifecycle VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', health_status VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
 source_purchase_item_id BIGINT UNSIGNED, replaced_by_asset_id BIGINT UNSIGNED, version INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(store_id,asset_code), UNIQUE(source_purchase_item_id), INDEX(store_id,lifecycle,health_status),
 CHECK(lifecycle IN ('ACTIVE','RETIRED')), CHECK(health_status IN ('NORMAL','FAULTY','REPAIRING')),
 FOREIGN KEY(store_id) REFERENCES repair_stores(id), FOREIGN KEY(replaced_by_asset_id) REFERENCES repair_assets(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
