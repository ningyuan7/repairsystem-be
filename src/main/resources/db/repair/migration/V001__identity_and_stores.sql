CREATE TABLE users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 phone VARCHAR(32) UNIQUE, email VARCHAR(128) UNIQUE, password_hash VARCHAR(255),
 nickname VARCHAR(64), avatar VARCHAR(512), bio VARCHAR(1000), zg_id VARCHAR(64) UNIQUE,
 gender VARCHAR(16), birthday DATE, school VARCHAR(128), tags_json JSON,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE login_logs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED,
 identifier VARCHAR(128), channel VARCHAR(32), ip VARCHAR(64), user_agent VARCHAR(1024), status VARCHAR(32),
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(user_id,created_at),
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_members (
 user_id BIGINT UNSIGNED PRIMARY KEY, role VARCHAR(32) NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 display_name VARCHAR(64) NOT NULL DEFAULT '', contact_phone VARCHAR(32) NOT NULL DEFAULT '',
 version INT UNSIGNED NOT NULL DEFAULT 0, auth_version INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CONSTRAINT ck_member_role CHECK(role IN ('HQ_ADMIN','STORE_MANAGER','ENGINEER')),
 CONSTRAINT ck_member_status CHECK(status IN ('ACTIVE','DISABLED')),
 INDEX(role,status), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_stores (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(32) NOT NULL UNIQUE, name VARCHAR(128) NOT NULL,
 region VARCHAR(64) NOT NULL DEFAULT '', address VARCHAR(255) NOT NULL DEFAULT '', status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 version INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CONSTRAINT ck_store_status CHECK(status IN ('ACTIVE','DISABLED')), INDEX(region,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_member_stores (
 user_id BIGINT UNSIGNED NOT NULL, store_id BIGINT UNSIGNED NOT NULL, PRIMARY KEY(user_id,store_id), INDEX(store_id,user_id),
 FOREIGN KEY(user_id) REFERENCES repair_members(user_id), FOREIGN KEY(store_id) REFERENCES repair_stores(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_invitations (
 id CHAR(36) PRIMARY KEY, email VARCHAR(128) NOT NULL, role VARCHAR(32) NOT NULL, store_ids JSON NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, expires_at DATETIME(3) NOT NULL, consumed_at DATETIME(3),
 inviter_id BIGINT UNSIGNED NOT NULL, version INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CONSTRAINT ck_invitation_role CHECK(role IN ('STORE_MANAGER','ENGINEER')),
 INDEX(email,expires_at), FOREIGN KEY(inviter_id) REFERENCES repair_members(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_system_locks (lock_name VARCHAR(64) PRIMARY KEY) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
