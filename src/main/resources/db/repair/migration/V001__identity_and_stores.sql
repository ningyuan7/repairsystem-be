CREATE TABLE repair_audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NOT NULL, action VARCHAR(64) NOT NULL,
 resource_type VARCHAR(32) NOT NULL, resource_id VARCHAR(64) NOT NULL, request_id VARCHAR(64) NOT NULL, summary JSON NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX(resource_type,resource_id,id), INDEX(actor_id,id), FOREIGN KEY(actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE repair_idempotency_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, operation VARCHAR(128) NOT NULL,
 idempotency_key CHAR(36) NOT NULL, request_hash CHAR(64) NOT NULL, auth_version INT UNSIGNED NOT NULL, http_status SMALLINT UNSIGNED NOT NULL,
 response_json JSON NOT NULL, expires_at DATETIME(3) NOT NULL,
 UNIQUE(user_id,operation,idempotency_key), INDEX(expires_at), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
